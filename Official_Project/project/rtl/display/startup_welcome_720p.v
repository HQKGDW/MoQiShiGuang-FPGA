`timescale 1ns/1ps

// Startup animation, drawn procedurally at 1280x720 / 60 fps.
//
//   t < AUDIO_LEAD_FRAMES   black (the animation itself is silent)
//   fade-in                 scene 1 fades in from black
//   scene 1 (brand)         gold rings expand from the centre, the gold rule
//                           opens, 默契食光 appears glyph by glyph with a light
//                           sweep, SILENT HARMONY drops in letter by letter,
//                           the tagline fades in
//   iris 1                  centre-out soft iris from scene 1 to scene 2,
//                           with the first transition sound
//   scene 2 (welcome)       欢迎光临 / WELCOME, progress bar, pulsing ring;
//                           waits here until the preload has finished
//   exit iris               centre-out soft iris into the main screen, with
//                           the second transition sound
//
// Glyphs are 2-bit anti-aliased bitmaps in BRAM32K, generated by
// tools/build_welcome_glyphs.py. Lines are exactly H_TOTAL clocks, so the scene
// is computed for pixels a few clocks ahead of the input and meets the live
// pixel at the last blend stage; vs/de/rgb leave the module two clocks later,
// aligned.
module startup_welcome_720p #(
    parameter integer H_ACTIVE = 1280,
    parameter integer H_TOTAL = 1650,     // clocks per line, blanking included
    parameter integer V_ACTIVE = 720,
    parameter integer MIN_FRAMES = 480,
    parameter integer AUDIO_LEAD_FRAMES = 18,
    parameter integer FADE_IN_FRAMES = 24,
    parameter integer SCENE1_FRAMES = 340,
    parameter integer IRIS_FRAMES = 45,
    parameter integer FADE_FRAMES = 45,
    parameter integer IRIS_STEP = 21,
    parameter integer BAR_STEP = 8          // progress bar glide, px per frame
) (
    input  wire        clk,
    input  wire        rst_n,
    input  wire        vs,
    input  wire        de,
    input  wire [23:0] rgb_in,
    input  wire [3:0]  resident_mask,
    input  wire [7:0]  load_progress,
    input  wire        asset_boot_done,
    // Every discovered category is resident or isolated as bad and no load is
    // pending: waiting longer cannot change the result.
    input  wire        preload_settled,
    output reg         vs_out,
    output reg         de_out,
    output reg  [23:0] rgb_out,
    output reg         welcome_active,
    output reg         welcome_done,
    output reg         chime_start,     // one clock: play a transition sound
    output reg         chime_exit       // with chime_start: 1 into the main screen
);
    localparam [23:0] CREAM       = 24'hf7f1e3;
    localparam [23:0] SWEEP_COLOR = 24'hfff4cf;
    localparam [23:0] GOLD        = 24'hd7a84b;
    localparam [23:0] GOLD_BRIGHT = 24'hf2d38a;
    localparam [23:0] TEXT_COLOR  = 24'hd7e5dc;
    localparam [23:0] MUTED_TEXT  = 24'h9fbab3;
    localparam [23:0] TRACK_COLOR = 24'h315b55;

    localparam [2:0] FG_CREAM = 3'd0;
    localparam [2:0] FG_SWEEP = 3'd1;
    localparam [2:0] FG_GOLD  = 3'd2;
    localparam [2:0] FG_TEXT  = 3'd3;
    localparam [2:0] FG_MUTED = 3'd4;

    localparam [2:0] PH_LEAD = 3'd0;
    localparam [2:0] PH_FADE = 3'd1;
    localparam [2:0] PH_S1   = 3'd2;
    localparam [2:0] PH_IRIS = 3'd3;
    localparam [2:0] PH_S2   = 3'd4;
    localparam [2:0] PH_EXIT = 3'd5;
    localparam [2:0] PH_DONE = 3'd6;

    // Layout in pixels.
    localparam integer TITLE_X  = 456;   // 4 glyphs on a 96 px advance, 80 px cells
    localparam integer TITLE_Y  = 196;
    localparam integer RULE_Y   = 300;
    localparam integer LATIN1_X = 416;   // SILENT HARMONY, 14 x 32 px
    localparam integer LATIN1_Y = 320;
    localparam integer TAG_X    = 416;   // tagline, 14 x 32 px
    localparam integer TAG_Y    = 390;
    localparam integer LATIN2_X = 504;   // WELCOME, 7 letters on a 40 px advance
    localparam integer LATIN2_Y = 300;
    localparam integer BAR_X    = 380;
    localparam integer BAR_Y    = 380;
    localparam integer BAR_W    = 520;
    localparam integer PROMPT_X = 544;   // 正在准备菜单, 6 x 32 px
    localparam integer PROMPT_Y = 424;

    // ------------------------------------------------------------------
    // Frame-level state.
    // ------------------------------------------------------------------
    reg [10:0] h5, h4;       // horizontal position of the pixel 5 / 4 clocks ahead
    reg        de4;          // that pixel (h4) is inside the active area
    reg [9:0]  line_y;
    reg        de_q;
    reg        vs_q;
    reg [9:0]  t;            // scripted time in frames, saturates
    reg [9:0]  tick;         // free-running frame count for periodic effects
    reg        exit_active;
    reg [6:0]  exit_frame;
    // Ring slots, set at frame start: R + w (w = half width) and brightness.
    // Slot 0 is ring 0 while it is on, otherwise the scene-2 pulse ring.
    reg [11:0] ring_b0, ring_b1, ring_b2;
    reg [7:0]  ring_lv0, ring_lv1, ring_lv2;
    reg        slot0_pulse, ring_on1, ring_on2;
    wire [11:0] ring_next0 = {t - 10'd20, 3'b000} + {t - 10'd20, 1'b0};
    wire [11:0] ring_next1 = {t - 10'd50, 3'b000} + {t - 10'd50, 1'b0};
    wire [11:0] ring_next2 = {t - 10'd80, 3'b000} + {t - 10'd80, 1'b0};
    wire [11:0] pulse_next = {2'b00, tick[6:0], 3'b000} + 12'd60;
    wire        ring_on_next0 = t >= 10'd20 && t < 10'd104;
    wire frame_start = !vs_q && vs;
    reg [10:0] progress_width;     // visible progress bar, only grows
    wire bar_full = progress_width == BAR_W;
    wire preload_complete = (resident_mask == 4'hf && asset_boot_done) ||
                            (preload_settled && resident_mask != 4'h0);

    reg [2:0] phase;
    always @* begin
        if (!welcome_active)
            phase = PH_DONE;
        else if (exit_active)
            phase = PH_EXIT;
        else if (t < AUDIO_LEAD_FRAMES)
            phase = PH_LEAD;
        else if (t < AUDIO_LEAD_FRAMES + FADE_IN_FRAMES)
            phase = PH_FADE;
        else if (t < SCENE1_FRAMES)
            phase = PH_S1;
        else if (t < SCENE1_FRAMES + IRIS_FRAMES)
            phase = PH_IRIS;
        else
            phase = PH_S2;
    end

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            h5 <= 11'd0; h4 <= 11'd0; de4 <= 1'b0;
            line_y <= 10'd0;
            de_q <= 1'b0;
            vs_q <= 1'b0;
            t <= 10'd0;
            tick <= 10'd0;
            exit_active <= 1'b0;
            exit_frame <= 7'd0;
            slot0_pulse <= 1'b1; ring_on1 <= 1'b0; ring_on2 <= 1'b0;
            ring_b0 <= 12'd0; ring_b1 <= 12'd0; ring_b2 <= 12'd0;
            ring_lv0 <= 8'd0; ring_lv1 <= 8'd0; ring_lv2 <= 8'd0;
            welcome_active <= 1'b1;
            welcome_done <= 1'b0;
            chime_start <= 1'b0;
            chime_exit <= 1'b0;
        end else begin
            de_q <= de;
            vs_q <= vs;
            chime_start <= 1'b0;

            // The first active clock of a line is position 0; re-align there.
            if (de && !de_q)
                h5 <= 11'd6;
            else
                h5 <= (h5 == H_TOTAL - 1) ? 11'd0 : h5 + 1'b1;
            h4 <= h5;
            de4 <= h5 < H_ACTIVE;

            if (vs)
                line_y <= 10'd0;
            else if (de_q && !de)
                line_y <= line_y + 1'b1;

            if (frame_start && welcome_active) begin
                tick <= tick + 1'b1;
                slot0_pulse <= !ring_on_next0;
                ring_on1 <= t >= 10'd50 && t < 10'd134;
                ring_on2 <= t >= 10'd80 && t < 10'd164;
                ring_b0 <= ring_on_next0 ? ring_next0 + 12'd2 : pulse_next + 12'd1;
                ring_b1 <= ring_next1 + 12'd2;
                ring_b2 <= ring_next2 + 12'd2;
                ring_lv0 <= ring_on_next0 ? ring_level(ring_next0) :
                            (pulse_next < 400) ? 8'd40 : (pulse_next < 700) ? 8'd20 : 8'd8;
                ring_lv1 <= ring_level(ring_next1);
                ring_lv2 <= ring_level(ring_next2);
                if (!(&t))
                    t <= t + 1'b1;
                if (t == SCENE1_FRAMES - 1) begin
                    chime_start <= 1'b1;            // iris into the welcome scene
                    chime_exit <= 1'b0;
                end
                if (exit_active) begin
                    if (exit_frame >= FADE_FRAMES - 1) begin
                        welcome_active <= 1'b0;
                        welcome_done <= 1'b1;
                    end else begin
                        exit_frame <= exit_frame + 1'b1;
                    end
                end else if (t >= SCENE1_FRAMES + IRIS_FRAMES &&
                             t >= MIN_FRAMES && preload_complete && bar_full) begin
                    exit_active <= 1'b1;
                    exit_frame <= 7'd0;
                    chime_start <= 1'b1;            // iris into the main screen
                    chime_exit <= 1'b1;
                end
            end
        end
    end

    // ------------------------------------------------------------------
    // Helpers.
    // ------------------------------------------------------------------
    function [4:0] sat16;             // clamp a signed frame difference to 0..16
        input signed [12:0] value;
        begin
            if (value <= 0) sat16 = 5'd0;
            else if (value >= 16) sat16 = 5'd16;
            else sat16 = value[4:0];
        end
    endfunction

    function [4:0] coverage_weight;   // 2-bit coverage -> 0..16
        input [1:0] coverage;
        begin
            case (coverage)
                2'd0: coverage_weight = 5'd0;
                2'd1: coverage_weight = 5'd6;
                2'd2: coverage_weight = 5'd11;
                default: coverage_weight = 5'd16;
            endcase
        end
    endfunction

    function [1:0] pick_pixel;        // 16 pixels per word, leftmost in [31:30]
        input [31:0] word;
        input [3:0] index;
        reg [31:0] shifted;
        begin
            shifted = word << {index, 1'b0};
            pick_pixel = shifted[31:30];
        end
    endfunction

    function [4:0] scale_weight;      // about (coverage weight * alpha) / 16
        input [4:0] weight;           // one of 0, 6, 11, 16
        input [4:0] alpha;            // 0..16
        begin
            case (weight)
                5'd16: scale_weight = alpha;
                5'd11: scale_weight = (alpha >> 1) + (alpha >> 3) + (alpha >> 4);
                5'd6:  scale_weight = (alpha >> 2) + (alpha >> 3);
                default: scale_weight = 5'd0;
            endcase
        end
    endfunction

    function [7:0] ring_level;        // rings fade as they grow
        input [11:0] radius;
        begin
            ring_level = (radius < 210) ? 8'd96 : (radius < 420) ? 8'd56 :
                         (radius < 630) ? 8'd28 : 8'd12;
        end
    endfunction

    function [7:0] blend8;            // a + (b - a) * w / 16, w = 0..16 (one DSP)
        input [7:0] a;
        input [7:0] b;
        input [4:0] w;
        reg signed [9:0] diff;
        reg signed [15:0] scaled;
        begin
            diff = $signed({2'b00, b}) - $signed({2'b00, a});
            scaled = diff * $signed({1'b0, w});
            blend8 = a + scaled[11:4];
        end
    endfunction

    function [23:0] blend24;
        input [23:0] a;
        input [23:0] b;
        input [4:0] w;
        begin
            blend24 = {blend8(a[23:16], b[23:16], w),
                       blend8(a[15:8], b[15:8], w),
                       blend8(a[7:0], b[7:0], w)};
        end
    endfunction

    function [23:0] fg_color;
        input [2:0] code;
        begin
            case (code)
                FG_SWEEP: fg_color = SWEEP_COLOR;
                FG_GOLD:  fg_color = GOLD;
                FG_TEXT:  fg_color = TEXT_COLOR;
                FG_MUTED: fg_color = MUTED_TEXT;
                default:  fg_color = CREAM;
            endcase
        end
    endfunction

    function [7:0] add_sat;
        input [7:0] a;
        input [7:0] b;
        reg [8:0] sum;
        begin
            sum = a + b;
            add_sat = sum[8] ? 8'hff : sum[7:0];
        end
    endfunction

    function [7:0] sub_sat;
        input [7:0] a;
        input [7:0] b;
        begin
            sub_sat = (a > b) ? a - b : 8'd0;
        end
    endfunction

    function [23:0] add_gold;         // additive warm highlight
        input [23:0] color;
        input [7:0] amount;
        begin
            add_gold = {add_sat(color[23:16], amount),
                        add_sat(color[15:8], amount - (amount >> 2)),
                        add_sat(color[7:0], amount >> 2)};
        end
    endfunction

    function [3:0] latin1_letter;     // SILENT HARMONY; 15 = blank
        input [3:0] index;
        begin
            case (index)
                4'd0: latin1_letter = 4'd0;   // S
                4'd1: latin1_letter = 4'd1;   // I
                4'd2: latin1_letter = 4'd2;   // L
                4'd3: latin1_letter = 4'd3;   // E
                4'd4: latin1_letter = 4'd4;   // N
                4'd5: latin1_letter = 4'd5;   // T
                4'd7: latin1_letter = 4'd6;   // H
                4'd8: latin1_letter = 4'd7;   // A
                4'd9: latin1_letter = 4'd8;   // R
                4'd10: latin1_letter = 4'd9;  // M
                4'd11: latin1_letter = 4'd10; // O
                4'd12: latin1_letter = 4'd4;  // N
                4'd13: latin1_letter = 4'd11; // Y
                default: latin1_letter = 4'd15;
            endcase
        end
    endfunction

    function [3:0] latin2_letter;     // WELCOME
        input [2:0] index;
        begin
            case (index)
                3'd0: latin2_letter = 4'd12;  // W
                3'd1: latin2_letter = 4'd3;   // E
                3'd2: latin2_letter = 4'd2;   // L
                3'd3: latin2_letter = 4'd13;  // C
                3'd4: latin2_letter = 4'd10;  // O
                3'd5: latin2_letter = 4'd9;   // M
                default: latin2_letter = 4'd3; // E
            endcase
        end
    endfunction

    // ------------------------------------------------------------------
    // Pixel pipeline.
    //
    //   root     distance from the centre, tracked along pixel h4
    //   stage 0  (h4) text cell counters, ROM addresses, distance flags,
    //            background gradient and gold dust
    //   stage 1  ROM data: text sample; rings / rule / glow / bar / rim
    //   stage 2  text blend
    //   stage 3  fade / iris blend; stage 3b meets the live input pixel
    //
    // line_y advances when de falls, more than 300 clocks before the next
    // line's first pixel enters stage 0 or the distance pipeline.
    //
    // Each pixel shows exactly one scene: scene 1 before the iris, scene 2
    // inside it.
    // ------------------------------------------------------------------
    localparam integer FADE_STEP = 256 / FADE_IN_FRAMES;   // weight per frame, x16

    // Frame-constant quantities, registered at frame start.
    reg [9:0]  rule_half;
    reg signed [12:0] sweep_pos;
    reg [4:0]  tag_alpha_frame;
    reg [4:0]  fade_weight;
    reg [10:0] iris_radius;
    reg [10:0] progress_target;    // furthest accepted progress
    reg [7:0]  load_progress_q;
    wire [10:0] progress_sample = preload_complete ? BAR_W[10:0] :
                                  {2'b00, load_progress, 1'b0} + (load_progress >> 5);
    wire        progress_sample_ok = preload_complete || load_progress == load_progress_q;
    wire [10:0] progress_step = preload_complete ? 4 * BAR_STEP : BAR_STEP;
    wire [10:0] progress_gap = progress_target - progress_width;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            load_progress_q <= 8'd0;
            progress_target <= 11'd0;
        end else begin
            load_progress_q <= load_progress;
            if (progress_sample_ok && progress_sample > progress_target)
                progress_target <= progress_sample;
        end
    end

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            rule_half <= 10'd0;
            sweep_pos <= 13'sd0;
            tag_alpha_frame <= 5'd0;
            fade_weight <= 5'd0;
            iris_radius <= 11'd0;
            progress_width <= 11'd0;
        end else if (frame_start) begin
            rule_half <= (t <= 24) ? 10'd0 : (t >= 56) ? 10'd380 :
                         {(t - 10'd24), 3'b000} + {(t - 10'd24), 2'b00};
            sweep_pos <= {($signed({3'b000, t}) - 13'sd100), 3'b000} +
                         {($signed({3'b000, t}) - 13'sd100), 1'b0} - 13'sd60;
            tag_alpha_frame <= sat16(($signed({3'b000, t}) - 13'sd120) >>> 1);
            fade_weight <= sat16((($signed({3'b000, t}) - AUDIO_LEAD_FRAMES) * FADE_STEP) >>> 4);
            iris_radius <= (phase == PH_IRIS) ? (t - SCENE1_FRAMES) * IRIS_STEP :
                                                exit_frame * IRIS_STEP;
            progress_width <= (progress_gap > progress_step) ? progress_width + progress_step :
                                                               progress_target;
        end
    end

    function [9:0] latin1_offset;     // glyph offset (letter * 72) for SILENT HARMONY
        input [3:0] index;
        reg [3:0] letter;
        begin
            letter = latin1_letter(index);
            latin1_offset = {letter, 6'd0} + {letter, 3'd0};
        end
    endfunction

    function [9:0] latin2_offset;     // glyph offset (letter * 72) for WELCOME
        input [2:0] index;
        reg [3:0] letter;
        begin
            letter = latin2_letter(index);
            latin2_offset = {letter, 6'd0} + {letter, 3'd0};
        end
    endfunction

    // ------------------------------------------------------------------
    // Distance from the centre for the stage-0 pixel h4, on a 16:9 grid
    // (dy weighted by 1.75) so rings and iris follow the screen shape.
    // iris_r = floor(sqrt((x - 640)^2 + dyw^2)), tracked incrementally: along a
    // line it changes by at most one per pixel, so one correction step per
    // clock keeps it exact. In horizontal blank the square is reset to the
    // next line's start and the root settles within a few clocks.
    // ------------------------------------------------------------------
    reg [9:0]  dy_abs;
    reg [10:0] dyw;
    reg [19:0] dyw_sq, line_start_sq;
    reg [19:0] dist_sq, root_sq;          // D for pixel h4, and root^2
    reg [9:0]  root;
    reg [19:0] dist_sq_next, root_up_sq, root_down_sq;
    reg signed [12:0] dist_step;
    wire [11:0] iris_r = {2'b00, root};

    always @* begin
        dy_abs = (line_y >= V_ACTIVE / 2) ? line_y - V_ACTIVE / 2 : V_ACTIVE / 2 - line_y;
        // (x - 640)^2 - (x - 641)^2 for the pixel entering stage 0 next clock.
        dist_step = $signed({1'b0, h5, 1'b0}) - 13'sd1281;
        if (h5 != 11'd0 && h5 < H_ACTIVE)
            dist_sq_next = dist_sq + {{7{dist_step[12]}}, dist_step};
        else
            dist_sq_next = line_start_sq;
        root_up_sq = root_sq + {9'd0, root, 1'b1};            // (r + 1)^2
        root_down_sq = root_sq - {9'd0, root - 1'b1, 1'b1};   // (r - 1)^2
    end

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            dyw <= 11'd0; dyw_sq <= 20'd0; line_start_sq <= 20'd0;
            dist_sq <= 20'd0; root_sq <= 20'd0; root <= 10'd0;
        end else begin
            dyw <= dy_abs + (dy_abs >> 1) + (dy_abs >> 2);
            dyw_sq <= dyw * dyw;
            line_start_sq <= 20'd409600 + dyw_sq;               // x = 0: dx = -640
            dist_sq <= dist_sq_next;
            if (dist_sq_next >= root_up_sq) begin
                root <= root + 1'b1;
                root_sq <= root_up_sq;
            end else if (dist_sq_next < root_sq) begin
                root <= root - 1'b1;
                root_sq <= root_down_sq;
            end
        end
    end

    // ------------------------------------------------------------------
    // Per-line constants for line_y (settled long before the line starts).
    // ------------------------------------------------------------------
    reg        title_row, latin2_row, tag_row, prompt_row;
    reg [11:0] title_row_offset;      // (y - TITLE_Y) * 5 words
    reg signed [12:0] sweep_line;     // (y - TITLE_Y) / 2 - sweep position
    reg signed [12:0] latin1_line;    // y - LATIN1_Y
    reg [9:0]  latin2_row_offset;     // (y - LATIN2_Y) * 2 words
    reg [10:0] tag_row_offset;        // (y - TAG_Y) * 2 words
    reg [10:0] prompt_row_offset;     // (y - PROMPT_Y) * 2 words
    reg signed [12:0] line_title, line_latin2, line_tag, line_prompt;

    always @* begin
        line_title  = $signed({3'b000, line_y}) - TITLE_Y;
        line_latin2 = $signed({3'b000, line_y}) - LATIN2_Y;
        line_tag    = $signed({3'b000, line_y}) - TAG_Y;
        line_prompt = $signed({3'b000, line_y}) - PROMPT_Y;
    end

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            title_row <= 1'b0; latin2_row <= 1'b0; tag_row <= 1'b0; prompt_row <= 1'b0;
            title_row_offset <= 12'd0; sweep_line <= 13'sd0; latin1_line <= 13'sd0;
            latin2_row_offset <= 10'd0; tag_row_offset <= 11'd0; prompt_row_offset <= 11'd0;
        end else begin
            title_row <= line_title >= 0 && line_title < 80;
            latin2_row <= line_latin2 >= 0 && line_latin2 < 36;
            tag_row <= line_tag >= 0 && line_tag < 32;
            prompt_row <= line_prompt >= 0 && line_prompt < 32;
            title_row_offset <= {line_title[6:0], 2'b00} + line_title[6:0];
            sweep_line <= (line_title >>> 1) - sweep_pos;
            latin1_line <= $signed({3'b000, line_y}) - LATIN1_Y;
            latin2_row_offset <= {line_latin2[5:0], 1'b0};
            tag_row_offset <= {line_tag[4:0], 1'b0};
            prompt_row_offset <= {line_prompt[4:0], 1'b0};
        end
    end

    // ------------------------------------------------------------------
    // Text cell counters. Each steps along pixel h5 so that its registered
    // value describes the stage-0 pixel h4.
    // ------------------------------------------------------------------
    reg        tc_on;  reg [1:0] tc_cell; reg [6:0] tc_x;   // titles:  456 + 96 n, 4 cells
    reg        lc_on;  reg [3:0] lc_cell; reg [4:0] lc_x;   // latin1 / tagline: 416 + 32 n, 14 cells
    reg        wc_on;  reg [2:0] wc_cell; reg [5:0] wc_x;   // WELCOME: 504 + 40 n, 7 cells
    reg        pc_on;  reg [2:0] pc_cell; reg [4:0] pc_x;   // prompt:  544 + 32 n, 6 cells
    reg signed [12:0] l1_v;            // t - 70 - 3 n for the current SILENT HARMONY letter
    reg [4:0]  l1_alpha;
    reg signed [12:0] l1_v_start, l1_v_next;

    always @* begin
        l1_v_start = $signed({3'b000, t}) - 13'sd70;
        l1_v_next = l1_v - 13'sd3;
    end

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            tc_on <= 1'b0; tc_cell <= 2'd0; tc_x <= 7'd0;
            lc_on <= 1'b0; lc_cell <= 4'd0; lc_x <= 5'd0;
            wc_on <= 1'b0; wc_cell <= 3'd0; wc_x <= 6'd0;
            pc_on <= 1'b0; pc_cell <= 3'd0; pc_x <= 5'd0;
            l1_v <= 13'sd0; l1_alpha <= 5'd0;
        end else if (h5 >= H_ACTIVE) begin
            tc_on <= 1'b0; lc_on <= 1'b0; wc_on <= 1'b0; pc_on <= 1'b0;
        end else begin
            if (h5 == TITLE_X) begin
                tc_on <= 1'b1; tc_cell <= 2'd0; tc_x <= 7'd0;
            end else if (tc_on) begin
                if (tc_x == 7'd95) begin
                    tc_x <= 7'd0;
                    if (tc_cell == 2'd3) tc_on <= 1'b0;
                    else tc_cell <= tc_cell + 1'b1;
                end else begin
                    tc_x <= tc_x + 1'b1;
                end
            end

            if (h5 == LATIN1_X) begin
                lc_on <= 1'b1; lc_cell <= 4'd0; lc_x <= 5'd0;
                l1_v <= l1_v_start; l1_alpha <= sat16(l1_v_start);
            end else if (lc_on) begin
                lc_x <= lc_x + 1'b1;
                if (lc_x == 5'd31) begin
                    if (lc_cell == 4'd13) begin
                        lc_on <= 1'b0;
                    end else begin
                        lc_cell <= lc_cell + 1'b1;
                        l1_v <= l1_v_next;
                        l1_alpha <= sat16(l1_v_next);
                    end
                end
            end

            if (h5 == LATIN2_X) begin
                wc_on <= 1'b1; wc_cell <= 3'd0; wc_x <= 6'd0;
            end else if (wc_on) begin
                if (wc_x == 6'd39) begin
                    wc_x <= 6'd0;
                    if (wc_cell == 3'd6) wc_on <= 1'b0;
                    else wc_cell <= wc_cell + 1'b1;
                end else begin
                    wc_x <= wc_x + 1'b1;
                end
            end

            if (h5 == PROMPT_X) begin
                pc_on <= 1'b1; pc_cell <= 3'd0; pc_x <= 5'd0;
            end else if (pc_on) begin
                pc_x <= pc_x + 1'b1;
                if (pc_x == 5'd31) begin
                    if (pc_cell == 3'd5) pc_on <= 1'b0;
                    else pc_cell <= pc_cell + 1'b1;
                end
            end
        end
    end

    // ------------------------------------------------------------------
    // Stage 0 (h4): scene choice, ROM addresses, distance-derived values.
    // ------------------------------------------------------------------
    reg        scene2, rim_hit, sweep_hit;
    reg signed [12:0] title_lx, sweep_d, l1_gy;
    reg [11:0] big_addr, big_addr1, big_addr2;
    reg [4:0]  title_alpha1;
    reg        title_region, latin1_region, latin2_region, tag_region, prompt_region;
    reg [9:0]  latin_addr, latin_addr1, latin_addr2;
    reg [10:0] small_addr, tag_addr, prompt_addr;
    reg        latin_region, small_region;
    reg [3:0]  sub_latin, sub_small;
    reg [4:0]  latin_alpha, small_alpha;
    reg [1:0]  text_kind;    // 0 none, 1 title, 2 latin, 3 small
    reg [4:0]  text_alpha;
    reg [7:0]  ring_add, glow;
    reg signed [12:0] ring_e0, ring_e1, ring_e2;   // (R + w) - r
    reg        ring_hit0, ring_hit1, ring_hit2;
    reg [11:0] glow_wide;
    reg signed [13:0] iris_delta;
    reg [4:0]  final_weight0;
    reg [7:0]  bg_r, bg_g, bg_b, vignette;
    reg [23:0] base_a;
    reg [9:0]  star_y;
    reg [7:0]  star_hash, star_hash2;
    reg        star_hit;
    reg [7:0]  star_amt, highlight_amt;
    reg        rule_hit, bar_hit, bar_fill, bar_shine;
    reg [10:0] bar_lx;
    reg [9:0]  shimmer;
    reg signed [12:0] t_signed;

    always @* begin
        t_signed = $signed({3'b000, t});

        iris_delta = $signed({3'b000, iris_radius}) - $signed({2'b00, iris_r});
        scene2 = (phase == PH_S2) || (phase == PH_EXIT) || (phase == PH_DONE) ||
                 (phase == PH_IRIS && iris_delta > 0);
        rim_hit = phase == PH_IRIS && iris_delta >= -3 && iris_delta <= 3;

        // Titles: 默契食光 (scene 1) and 欢迎光临 (scene 2) share one grid.
        title_region = title_row && tc_on && tc_x < 7'd80;
        // Scene 1 glyphs 0-3; scene 2: 欢 迎 光 临 are glyphs 4, 5, 3, 6.
        big_addr1 = ((tc_cell == 2'd0) ? 12'd0 : (tc_cell == 2'd1) ? 12'd400 :
                     (tc_cell == 2'd2) ? 12'd800 : 12'd1200) + title_row_offset + tc_x[6:4];
        big_addr2 = ((tc_cell == 2'd0) ? 12'd1600 : (tc_cell == 2'd1) ? 12'd2000 :
                     (tc_cell == 2'd2) ? 12'd1200 : 12'd2400) + title_row_offset + tc_x[6:4];
        big_addr = scene2 ? big_addr2 : big_addr1;
        title_alpha1 = sat16(t_signed - 13'sd40 - {8'd0, tc_cell, 3'b000});
        title_lx = $signed({2'b00, h4}) - TITLE_X;
        sweep_d = title_lx + sweep_line;
        sweep_hit = !scene2 && t >= 100 && t < 170 && sweep_d >= 0 && sweep_d < 40;

        // SILENT HARMONY drops in letter by letter; WELCOME sits still.
        l1_gy = latin1_line + $signed({7'd0, 5'd16 - l1_alpha, 1'b0});
        latin1_region = lc_on && lc_cell != 4'd6 && l1_gy >= 0 && l1_gy < 36;
        latin_addr1 = latin1_offset(lc_cell) + {l1_gy[5:0], 1'b0} + lc_x[4];
        latin2_region = latin2_row && wc_on && wc_x < 6'd32;
        latin_addr2 = latin2_offset(wc_cell) + latin2_row_offset + wc_x[4];
        if (!scene2) begin
            latin_region = latin1_region;
            latin_addr = latin_addr1;
            sub_latin = lc_x[3:0];
            latin_alpha = l1_alpha;
        end else begin
            latin_region = latin2_region;
            latin_addr = latin_addr2;
            sub_latin = wc_x[3:0];
            latin_alpha = 5'd16;
        end

        // Tagline (scene 1) and loading prompt (scene 2).
        tag_region = tag_row && lc_on;
        tag_addr = {lc_cell, 6'd0} + tag_row_offset + lc_x[4];
        prompt_region = prompt_row && pc_on;
        prompt_addr = {(5'd14 + {2'b00, pc_cell}), 6'd0} + prompt_row_offset + pc_x[4];
        if (!scene2) begin
            small_region = tag_region;
            small_addr = tag_addr;
            sub_small = lc_x[3:0];
            small_alpha = tag_alpha_frame;
        end else begin
            small_region = prompt_region;
            small_addr = prompt_addr;
            sub_small = pc_x[3:0];
            small_alpha = 5'd16;
        end

        // At most one text element covers any pixel.
        if (!de4) begin
            text_kind = 2'd0; text_alpha = 5'd0;
        end else if (title_region) begin
            text_kind = 2'd1; text_alpha = scene2 ? 5'd16 : title_alpha1;
        end else if (latin_region) begin
            text_kind = 2'd2; text_alpha = latin_alpha;
        end else if (small_region) begin
            text_kind = 2'd3; text_alpha = small_alpha;
        end else begin
            text_kind = 2'd0; text_alpha = 5'd0;
        end

        // Distance-derived decorations.
        // |r - R| <= w  <=>  0 <= (R + w) - r <= 2w; rings w = 2, pulse w = 1.
        ring_e0 = $signed({1'b0, ring_b0}) - $signed({1'b0, iris_r});
        ring_e1 = $signed({1'b0, ring_b1}) - $signed({1'b0, iris_r});
        ring_e2 = $signed({1'b0, ring_b2}) - $signed({1'b0, iris_r});
        ring_hit0 = ring_e0[12:3] == 10'd0 && ring_e0[2:0] <= (slot0_pulse ? 3'd2 : 3'd4);
        ring_hit1 = ring_on1 && ring_e1[12:3] == 10'd0 && ring_e1[2:0] <= 3'd4;
        ring_hit2 = ring_on2 && ring_e2[12:3] == 10'd0 && ring_e2[2:0] <= 3'd4;
        // Rings belong to scene 1, the pulse ring to scene 2.
        ring_add = 8'd0;
        if (ring_hit0 && (slot0_pulse ? scene2 : !scene2)) ring_add = ring_lv0;
        if (ring_hit1 && !scene2) ring_add = ring_lv1;
        if (ring_hit2 && !scene2) ring_add = ring_lv2;
        glow_wide = (iris_r < 320) ? (12'd320 - iris_r) >> 4 : 12'd0;
        glow = glow_wide[7:0];

        // Exit iris: soft edge, 0 outside the radius, 16 once 32 px inside it.
        if (iris_delta <= 0)
            final_weight0 = 5'd0;
        else if (iris_delta >= 32)
            final_weight0 = 5'd16;
        else
            final_weight0 = iris_delta[5:1];
        if (phase == PH_FADE)
            final_weight0 = fade_weight;

        // Deep teal vertical gradient with a soft vignette.
        vignette = {2'b00, iris_r[11:6]};
        bg_r = sub_sat(8'h06 + line_y[9:7], vignette >> 1);
        bg_g = sub_sat(8'h24 + line_y[9:5], vignette);
        bg_b = sub_sat(8'h20 + line_y[9:5], vignette);
        base_a = {bg_r, bg_g, bg_b};

        // Rising gold dust: at most one 2x2 mote per 32x32 cell (XOR hash).
        star_y = line_y + {tick[8:0], 1'b0};
        star_hash = {h4[10:5], 2'b01} ^ {star_y[9:5], 3'b101} ^
                    {h4[7:5], star_y[9:5]} ^ {star_y[6:5], h4[10:5]};
        star_hash2 = {star_y[9:5], h4[10:8]} ^ {h4[7:5], star_y[9:5]} ^ 8'h5a;
        star_hit = star_hash[7:5] == 3'b101 &&
                   h4[4:1] == star_hash2[3:0] && star_y[4:1] == star_hash2[7:4];
        star_amt = star_hit ? ((star_hash[1:0] == tick[6:5]) ? 8'd80 : 8'd36) : 8'd0;
        highlight_amt = add_sat(star_amt, ring_add);

        // Gold rule (scene 1) and progress bar (scene 2).
        rule_hit = line_y >= RULE_Y && line_y < RULE_Y + 3 &&
                   h4 + rule_half >= H_ACTIVE / 2 && h4 < H_ACTIVE / 2 + rule_half;
        bar_lx = h4 - BAR_X;
        shimmer = bar_lx[9:0] - {tick[6:0], 3'b000};
        bar_hit = line_y >= BAR_Y && line_y < BAR_Y + 8 && h4 >= BAR_X && h4 < BAR_X + BAR_W;
        bar_fill = bar_lx < progress_width;
        bar_shine = shimmer[7:0] < 8'd28;
    end

    // ------------------------------------------------------------------
    // Glyph ROMs (synchronous; data lines up with stage 1).
    // ------------------------------------------------------------------
    wire [31:0] big_word, latin_word, small_word;

    welcome_glyph_rom #(.DEPTH(2800), .ADDR_W(12), .FILE("welcome_big")) u_big_rom (
        .clk(clk), .addr(big_addr), .data(big_word));
    welcome_glyph_rom #(.DEPTH(1008), .ADDR_W(10), .FILE("welcome_latin")) u_latin_rom (
        .clk(clk), .addr(latin_addr), .data(latin_word));
    welcome_glyph_rom #(.DEPTH(1280), .ADDR_W(11), .FILE("welcome_small")) u_small_rom (
        .clk(clk), .addr(small_addr), .data(small_word));

    // ------------------------------------------------------------------
    // Stage 1 registers.
    // ------------------------------------------------------------------
    reg        s1_scene2, s1_sweep, s1_rim;
    reg [23:0] s1_base_a;
    reg        s1_rule, s1_bar, s1_bar_fill, s1_bar_shine;
    reg [1:0]  s1_text_kind;
    reg [4:0]  s1_text_alpha, s1_final;
    reg [3:0]  s1_sub_big, s1_sub_latin, s1_sub_small;
    reg [7:0]  s1_highlight, s1_glow;
    reg [2:0]  s1_phase;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            s1_scene2 <= 1'b0; s1_sweep <= 1'b0; s1_rim <= 1'b0;
            s1_base_a <= 24'd0;
            s1_rule <= 1'b0; s1_bar <= 1'b0; s1_bar_fill <= 1'b0; s1_bar_shine <= 1'b0;
            s1_text_kind <= 2'd0; s1_text_alpha <= 5'd0; s1_final <= 5'd0;
            s1_sub_big <= 4'd0; s1_sub_latin <= 4'd0; s1_sub_small <= 4'd0;
            s1_highlight <= 8'd0; s1_glow <= 8'd0;
            s1_phase <= PH_LEAD;
        end else begin
            s1_scene2 <= scene2; s1_sweep <= sweep_hit; s1_rim <= rim_hit;
            s1_base_a <= base_a;
            s1_rule <= rule_hit; s1_bar <= bar_hit; s1_bar_fill <= bar_fill; s1_bar_shine <= bar_shine;
            s1_text_kind <= text_kind; s1_text_alpha <= text_alpha; s1_final <= final_weight0;
            s1_sub_big <= tc_x[3:0]; s1_sub_latin <= sub_latin; s1_sub_small <= sub_small;
            s1_highlight <= highlight_amt; s1_glow <= glow;
            s1_phase <= phase;
        end
    end

    // ------------------------------------------------------------------
    // Stage 1: scene decorations and the text sample.
    // ------------------------------------------------------------------
    reg [23:0] base;
    reg [2:0]  fg;           // text colour code, see fg_color
    reg [4:0]  w_text;
    reg [1:0]  coverage;
    reg [7:0]  amount;
    wire [4:0] final_weight = s1_final;

    always @* begin
        // Gold dust, rings and the pulse ring arrive as one summed amount;
        // solid elements (rule, progress bar) replace it. The iris rim adds on
        // top of everything, then a single saturating gold add is applied.
        base = s1_base_a;
        amount = s1_highlight;
        if (!s1_scene2) begin
            // Scene 1: the gold rule.
            if (s1_rule) begin
                base = GOLD;
                amount = 8'd0;
            end
        end else begin
            // Scene 2: warm glow and the progress bar.
            base = {add_sat(base[23:16], s1_glow >> 1), add_sat(base[15:8], s1_glow),
                    add_sat(base[7:0], s1_glow - (s1_glow >> 2))};
            if (s1_bar) begin
                base = s1_bar_fill ? (s1_bar_shine ? GOLD_BRIGHT : GOLD) : TRACK_COLOR;
                amount = 8'd0;
            end
        end
        if (s1_rim)
            amount = add_sat(amount, 8'd110);
        base = add_gold(base, amount);

        case (s1_text_kind)
            2'd1: begin
                coverage = pick_pixel(big_word, s1_sub_big);
                fg = s1_sweep ? FG_SWEEP : FG_CREAM;
            end
            2'd2: begin
                coverage = pick_pixel(latin_word, s1_sub_latin);
                fg = FG_GOLD;
            end
            2'd3: begin
                coverage = pick_pixel(small_word, s1_sub_small);
                fg = s1_scene2 ? FG_MUTED : FG_TEXT;
            end
            default: begin
                coverage = 2'd0;
                fg = FG_CREAM;
            end
        endcase
    end

    // Stage 1b: register the ROM-derived sample before weighting it.
    reg [23:0] s1b_base;
    reg [2:0]  s1b_fg;
    reg [1:0]  s1b_coverage;
    reg [4:0]  s1b_alpha, s1b_final;
    reg [2:0]  s1b_phase;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            s1b_base <= 24'd0; s1b_fg <= FG_CREAM; s1b_coverage <= 2'd0;
            s1b_alpha <= 5'd0; s1b_final <= 5'd0; s1b_phase <= PH_LEAD;
        end else begin
            s1b_base <= base; s1b_fg <= fg; s1b_coverage <= coverage;
            s1b_alpha <= s1_text_alpha; s1b_final <= final_weight; s1b_phase <= s1_phase;
        end
    end

    always @* begin
        w_text = scale_weight(coverage_weight(s1b_coverage), s1b_alpha);
    end

    // ------------------------------------------------------------------
    // Stage 2 / 3 registers and output.
    // ------------------------------------------------------------------
    reg [23:0] s2_base;
    reg [2:0]  s2_fg;
    reg [4:0]  s2_w, s2_final, s3_final;
    reg [2:0]  s2_phase, s3_phase;
    reg [23:0] s3_scene;
    reg [23:0] mixed, mix_from, mix_to;
    reg        s3b_de, s3b_vs;
    reg [2:0]  s3b_phase;
    reg [23:0] s3b_rgb_in, s3b_scene, s3b_from;   // s3b_from: combinational
    reg signed [15:0] s3b_r, s3b_g, s3b_b;

    function signed [15:0] blend_product;   // (b - a) * w, the multiply of blend8
        input [7:0] a;
        input [7:0] b;
        input [4:0] w;
        reg signed [9:0] diff;
        begin
            diff = $signed({2'b00, b}) - $signed({2'b00, a});
            blend_product = diff * $signed({1'b0, w});
        end
    endfunction

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            s2_base <= 24'd0; s2_fg <= FG_CREAM; s2_w <= 5'd0; s2_final <= 5'd0;
            s2_phase <= PH_LEAD;
            s3_scene <= 24'd0; s3_final <= 5'd0; s3_phase <= PH_LEAD;
            s3b_de <= 1'b0; s3b_vs <= 1'b0; s3b_phase <= PH_LEAD;
            s3b_rgb_in <= 24'd0; s3b_scene <= 24'd0;
            s3b_r <= 16'sd0; s3b_g <= 16'sd0; s3b_b <= 16'sd0;
            vs_out <= 1'b0; de_out <= 1'b0; rgb_out <= 24'd0;
        end else begin
            s2_base <= s1b_base; s2_fg <= s1b_fg; s2_w <= w_text; s2_final <= s1b_final;
            s2_phase <= s1b_phase;

            s3_scene <= blend24(s2_base, fg_color(s2_fg), s2_w);
            s3_final <= s2_final; s3_phase <= s2_phase;

            // s3 holds the scene for the pixel arriving now.
            s3b_de <= de; s3b_vs <= vs; s3b_phase <= s3_phase;
            s3b_rgb_in <= rgb_in; s3b_scene <= s3_scene;
            s3b_r <= blend_product(mix_from[23:16], mix_to[23:16], s3_final);
            s3b_g <= blend_product(mix_from[15:8], mix_to[15:8], s3_final);
            s3b_b <= blend_product(mix_from[7:0], mix_to[7:0], s3_final);

            vs_out <= s3b_vs; de_out <= s3b_de;
            rgb_out <= mixed;
        end
    end

    always @* begin
        if (s3_phase == PH_FADE) begin
            mix_from = 24'h000000; mix_to = s3_scene;
        end else begin
            mix_from = s3_scene; mix_to = rgb_in;
        end
        // The fade starts from black, the exit iris from the scene.
        s3b_from = (s3b_phase == PH_FADE) ? 24'h000000 : s3b_scene;
        case (s3b_phase)
            PH_LEAD: mixed = 24'h000000;
            PH_DONE: mixed = s3b_rgb_in;
            PH_FADE, PH_EXIT: mixed = {s3b_from[23:16] + s3b_r[11:4],
                                       s3b_from[15:8] + s3b_g[11:4],
                                       s3b_from[7:0] + s3b_b[11:4]};
            default: mixed = s3b_scene;
        endcase
        if (!s3b_de && s3b_phase != PH_DONE)
            mixed = 24'h000000;
    end
endmodule

// Single-port glyph table in BRAM32K.
module welcome_glyph_rom #(
    parameter integer DEPTH = 1024,
    parameter integer ADDR_W = 10,
    parameter FILE = "welcome_big"
) (
    input  wire              clk,
    input  wire [ADDR_W-1:0] addr,
    output wire [31:0]       data
);
`ifdef ORDER_UI_SIMULATION
reg [31:0] simulation_rom [0:DEPTH-1];
reg [31:0] simulation_data;
initial $readmemh({"../../project/rtl/display/", FILE, ".dath"}, simulation_rom);
always @(posedge clk)
    simulation_data <= (addr < DEPTH) ? simulation_rom[addr] : 32'd0;
assign data = simulation_data;
`else
EG_LOGIC_BRAM #(
    .DATA_WIDTH_A(32), .ADDR_WIDTH_A(ADDR_W), .DATA_DEPTH_A(DEPTH),
    .DATA_WIDTH_B(32), .ADDR_WIDTH_B(ADDR_W), .DATA_DEPTH_B(DEPTH),
    .MODE("SP"), .REGMODE_A("NOREG"), .IMPLEMENT("32K"),
    .DEBUGGABLE("NO"), .PACKABLE("NO"),
    .INIT_FILE({FILE, ".mif"}), .FILL_ALL("NONE")
) u_bram (
    .dia(32'd0), .dib(32'd0), .addra(addr), .addrb({ADDR_W{1'b0}}),
    .cea(1'b1), .ceb(1'b0), .ocea(1'b0), .oceb(1'b0),
    .clka(clk), .clkb(1'b0), .wea(1'b0), .web(1'b0),
    .bea(1'b0), .beb(1'b0), .rsta(1'b0), .rstb(1'b0),
    .doa(data), .dob()
);
`endif
endmodule
